    @classmethod
    def get_unseong(cls, day_gan: CheonGan, target_ji: JiJi) -> str:
        """
        특정 지지에서 일간의 운성 반환

        Args:
            day_gan: 일간
            target_ji: 대상 지지 (년지, 월지, 일지, 시지 등)

        Returns:
            운성 이름
        """
        gan_index = day_gan.index
        ji_index = target_ji.index

        if gan_index in cls.UNSEONG_TABLE:
            return cls.UNSEONG_TABLE[gan_index].get(ji_index, "알수없음")

        return "알수없음"

    @classmethod
    def analyze_saju_unseong(
        cls,
        day_gan: CheonGan,
        year_ji: JiJi,
        month_ji: JiJi,
        day_ji: JiJi,
        hour_ji: JiJi
    ) -> Dict:
        """
        사주 사기둥의 십이운성 분석

        Returns:
            {
                "year": {"unseong": "장생", "meaning": {...}},
                "month": {...},
                "day": {...},
                "hour": {...},
                "strongest": "제왕",
                "summary": "..."
            }
        """
        jis = {
            "year": year_ji,
            "month": month_ji,
            "day": day_ji,
            "hour": hour_ji
        }

        result = {}
        unseong_list = []

        for position, ji in jis.items():
            unseong_name = cls.get_unseong(day_gan, ji)
            unseong_list.append(unseong_name)

            result[position] = {
                "unseong": unseong_name,
                "meaning": cls.UNSEONG_MEANING.get(unseong_name, {}),
                "ji": f"{ji.korean}({ji.hanja})"
            }

        # 가장 강한 운성 찾기
        strength_order = ["제왕", "건록", "장생", "관대", "양", "태", "쇠", "묘", "목욕", "병", "사", "절"]
        strongest = None
        for unseong in strength_order:
            if unseong in unseong_list:
                strongest = unseong
                break

        result["strongest"] = strongest
        result["summary"] = cls._generate_summary(unseong_list, strongest)

        return result

    @classmethod
    def _generate_summary(cls, unseong_list: list, strongest: str) -> str:
        """십이운성 요약 생성"""
        # 길한 운성 개수
        good = sum(1 for u in unseong_list if u in ["장생", "건록", "제왕", "관대", "양"])
        bad = sum(1 for u in unseong_list if u in ["병", "사", "절"])

        summary = f"강한 운성: {strongest}"

        if good >= 3:
            summary += " | 길한 기운이 강함"
        elif bad >= 2:
            summary += " | 어려움이 있으나 극복 가능"

        return summary
